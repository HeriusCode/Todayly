// 3. Get Outfit by ID
export const getOutfitById = async (req, res, next) => {
  try {
    if (!isConnected) return res.status(503).json({ message: 'Cơ sở dữ liệu đang kết nối.' });

    const { id } = req.params;
    let outfit = null;

    if (mongoose.isValidObjectId(id)) {
      outfit = await Outfit.findById(id);
    } else {
      outfit = await Outfit.findOne({ externalId: id });
    }

    if (!outfit) {
      return res.status(404).json({ message: 'Không tìm thấy gợi ý trang phục.' });
    }

    res.json(outfit);
  } catch (error) {
    next(error);
  }
};

